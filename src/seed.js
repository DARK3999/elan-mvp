export function seed() {
  initSchema();
  const insert = db.prepare(`
    INSERT OR REPLACE INTO resources
    (id, title, type, author, category, level, language, cost, url, duration, context, objective, blocker, status, source)
    VALUES (@id, @title, @type, @author, @category, @level, 'fr', @cost, @url, @duration, @context, @objective, @blocker, @status, @source)
  `);
  db.exec('BEGIN');
  try {
    for (const r of RESOURCES) insert.run(r);
    db.exec('COMMIT');
  } catch (e) {
    db.exec('ROLLBACK');
    throw e;
  }
  console.log(`✅ ${RESOURCES.length} ressources insérées.`);
}

